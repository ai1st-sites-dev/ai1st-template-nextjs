'use strict';
// ══════════════════════════════════════════════════════════════════════════════════════════════════
// scaffolding-pool.js — 「今天的主题池是不是脚手架池」这一个判据，全仓只有这一份（#1317）
// ══════════════════════════════════════════════════════════════════════════════════════════════════
//
// #1317（2026-09-14）把 `theme-pool.json` 从 97 套删到 2 套：整池要按新框架重新生成，重建期只留
// 能测「换主题」这件事的最小数（Chris 2026-09-14 拍板，设计文档 D0）。
//
// 后果是七份测试里有一批格子**按构造**红 —— 不是代码坏了，是它们问的问题在 2 套的池子上没有对象
// 可问（「每种 hero 画法至少 8 套」「16 个行业组两两候选集合不同」「池里要有一套透明浮层顶栏」…）。
// 这些格子要跳过，但跳过必须**说出来**：
//
// 🔴 **不许静默绿。** 一个什么都没跑的绿跟「全过」长得一模一样，而这一批格子守的正是这条流水线
//    最贵的那些性质。所以下面那个函数**打印一行再返回 true**，调用方按它跳，并且**不记 pass**
//    （每份测试自己有一个 skip 计数，汇总行上单独列）。
//
// 🔴 **门控的判据是池子大小，不是一张格子名单。** 写成名单的话，池子长回去那天没人会想起来把
//    名单拆掉，而那时这些格子会继续静默跳过 —— 那才是真正会咬人的失明。写成大小，池子一重生成
//    它们自己就全部回来。
//
// 🔴 **门槛 10 的理由**：`themes.js` 的 `MIN_ROTATION_POOL` 是 3，而 #1007 那条产品要求是「一个
//    行业至少 10 套候选」（`pool.test.js` ① 与 `industry-sectors.test.js` AC1 钉的就是它）。也就是
//    10 是「这池数据开始能回答那些问题」的下限。低于它，那些问题没有对象。
const path = require('path');

const POOL_FILE = path.resolve(__dirname, '..', 'theme-pool.json');

// 🔴 `require()` 有模块缓存 —— 这个数在**一个进程之内是个常量**，改盘上那份文件不会让它跟着变
// （#1317 r1 这里写的是「每次现读，不缓存」，那句话是假的，QA1 实测：同一进程里把盘上的池子改成
// 12 套，两次读到的都是 2）。
//
// 🔴 **不要改成 `fs.readFileSync` 去把那句话变成真的** —— 那样更糟：被测的那一侧
// （`themes.js` 的 `require('./theme-pool.json')`、`skeleton-distance.test.js` 同款）照样
// 是缓存的，于是门控读到新池子、而它门控的那些格子读到的还是旧池子 —— 门控跟被测对象各说各话。
//
// ⟹ 反向对照的做法是**改盘上的文件，另起一个进程**（QA1 在 r1 上就是这么做的：池子 2 → 10，
//    七份门控文件的跳过行全部归零、pool.test.js 那 17 格红当场回来）。
/** 今天池子里有几套。 */
function poolSize() {
  // eslint-disable-next-line global-require
  return Object.keys(require(POOL_FILE)).length;
}

/** 脚手架期？（池子小于 10 套） */
function isScaffoldingPool() {
  return poolSize() < 10;
}

/**
 * 命中就打印一行并返回 true，调用方 `if (skipOnScaffoldingPool('① 行业覆盖度')) { … } else { … }`。
 * `why` 是「这一格在 2 套的池子上为什么没有对象可问」，一句话，写给下一个人看。
 */
function skipOnScaffoldingPool(what, why) {
  if (!isScaffoldingPool()) return false;
  console.log(`  ⏭  ${what} —— 脚手架池，跳过（池子只有 ${poolSize()} 套，#1317 重建期）`
    + (why ? `：${why}` : '')
    + '\n     🔴 这不是通过。池子重新生成到 ≥10 套那天，这一格自己就回来了（判据是池子大小，'
    + '不是一张名单）—— 那天要连同它的读数一起重新看一遍。');
  return true;
}

module.exports = { poolSize, isScaffoldingPool, skipOnScaffoldingPool };
